-- =====================================================================================================
-- V1: identity schema as used by FinSphere Nexus 1.x (previously created by hand / Hibernate).
-- Fresh databases get it from here. Existing 1.x databases are baselined at V1 (spring.flyway.baseline-on-migrate)
-- and only receive V2+. Schema: fsn_identity (Flyway default schema).
-- =====================================================================================================

CREATE TABLE IF NOT EXISTS users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(15)  NOT NULL,
    email        VARCHAR(100),
    password     VARCHAR(255) NOT NULL,
    role         VARCHAR(255) NOT NULL,
    is_active    BOOLEAN      NOT NULL,
    created_at   TIMESTAMP(6),
    CONSTRAINT uk_users_phone_number UNIQUE (phone_number),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_user_phone ON users (phone_number);
CREATE INDEX IF NOT EXISTS idx_user_email ON users (email);

CREATE TABLE IF NOT EXISTS customer_profiles (
    user_id   BIGINT NOT NULL PRIMARY KEY,
    full_name VARCHAR(100),
    care_of   VARCHAR(100),
    address   VARCHAR(500),
    CONSTRAINT fk_customer_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS login_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT,
    phone_number VARCHAR(255),
    email        VARCHAR(255),
    action_type  VARCHAR(255) NOT NULL,
    ip_address   VARCHAR(255),
    user_agent   VARCHAR(255),
    remarks      VARCHAR(255),
    created_at   TIMESTAMP(6)
);
