-- V2: FinSphere Nexus 2.0 identity changes
--   * clean e-mail data (blank -> NULL, lower-case) and enforce case-insensitive uniqueness
--   * audit columns + optimistic locking for users (AuditableEntity)
--   * timestamps become TIMESTAMPTZ. 1.x stored local wall-clock times, so they are read in the zone the
--     1.x services ran in: Flyway placeholder legacy-time-zone (env FSN_LEGACY_TIME_ZONE, default Asia/Kolkata)
--   * login_audit fits real user agents and carries correlation ids
--   * transactional outbox for Kafka events
