-- 1. E-mail clean-up: 1.x stored "" for "no e-mail", which allowed only one such user
UPDATE users SET email = NULL WHERE email IS NOT NULL AND btrim(email) = '';

-- 1.x compared e-mails case-sensitively, so "Ravi@x.com" and "ravi@x.com" could belong to two accounts. The oldest
-- account keeps the address; the others lose it (they still sign in with their phone number) and are listed in
-- user_email_conflicts for an administrator to follow up.
CREATE TABLE IF NOT EXISTS user_email_conflicts (
    user_id      BIGINT PRIMARY KEY,
    email        VARCHAR(100) NOT NULL,
    kept_user_id BIGINT       NOT NULL,
    detected_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
INSERT INTO user_email_conflicts (user_id, email, kept_user_id)
SELECT id, email, kept_id
FROM (SELECT id, email, first_value(id) OVER (PARTITION BY lower(btrim(email)) ORDER BY id) AS kept_id
      FROM users
      WHERE email IS NOT NULL) ranked
WHERE id <> kept_id
ON CONFLICT (user_id) DO NOTHING;
UPDATE users SET email = NULL WHERE id IN (SELECT user_id FROM user_email_conflicts);
DO $$
DECLARE
    conflicts INTEGER;
BEGIN
    SELECT count(*) INTO conflicts FROM user_email_conflicts;
    IF conflicts > 0 THEN
        RAISE WARNING '% account(s) shared an e-mail address with an older account and had it removed. Review table user_email_conflicts.', conflicts;
    END IF;
END
$$;
UPDATE users SET email = lower(btrim(email)) WHERE email IS NOT NULL AND email <> lower(btrim(email));

