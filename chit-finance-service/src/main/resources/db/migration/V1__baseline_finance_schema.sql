-- =====================================================================================================
-- V1: finance schema exactly as Hibernate (ddl-auto=update) created it for FinSphere Nexus 1.x.
-- Fresh databases get it from here. Existing 1.x databases are baselined at V1 (spring.flyway.baseline-on-migrate)
-- and only receive V2+. Schema: fsn_finance (Flyway default schema).
-- =====================================================================================================

CREATE TABLE IF NOT EXISTS chit_plans (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commission_amount     NUMERIC(38, 2),
    commission_percentage NUMERIC(38, 2) NOT NULL,
    created_at            TIMESTAMP(6),
    created_by            BIGINT,
    duration_months       INTEGER        NOT NULL,
    end_date              DATE,
    is_active             BOOLEAN,
    max_bid_limit         NUMERIC(38, 2) NOT NULL,
    monthly_installment   NUMERIC(38, 2) NOT NULL,
    name                  VARCHAR(255)   NOT NULL,
    start_date            DATE           NOT NULL,
    total_members         INTEGER        NOT NULL,
    total_value           NUMERIC(38, 2) NOT NULL,
    updated_at            TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS chit_monthly_cycles (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_winner_bid      NUMERIC(38, 2),
    created_at              TIMESTAMP(6),
    dividend_per_member     NUMERIC(38, 2),
    is_cycle_closed         BOOLEAN,
    monthly_count           INTEGER        NOT NULL,
    monthly_payable_amount  NUMERIC(38, 2) NOT NULL,
    payment_window_deadline DATE           NOT NULL,
    payment_window_start    DATE           NOT NULL,
    winner_user_id          BIGINT,
    plan_id                 BIGINT         NOT NULL,
    CONSTRAINT fk_cycles_plan FOREIGN KEY (plan_id) REFERENCES chit_plans (id)
);

CREATE INDEX IF NOT EXISTS idx_monthly_plan_id ON chit_monthly_cycles (plan_id);
CREATE INDEX IF NOT EXISTS idx_monthly_winner_user ON chit_monthly_cycles (winner_user_id);
CREATE INDEX IF NOT EXISTS idx_monthly_plan_count ON chit_monthly_cycles (plan_id, monthly_count);

CREATE TABLE IF NOT EXISTS chit_enrollments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_active   BOOLEAN,
    joined_date TIMESTAMP(6),
    slot_number INTEGER NOT NULL,
    user_id     BIGINT  NOT NULL,
    plan_id     BIGINT  NOT NULL,
    CONSTRAINT fk_enrollments_plan FOREIGN KEY (plan_id) REFERENCES chit_plans (id)
);

CREATE INDEX IF NOT EXISTS idx_enrollment_user_id ON chit_enrollments (user_id);
CREATE INDEX IF NOT EXISTS idx_enrollment_plan_id ON chit_enrollments (plan_id);

CREATE TABLE IF NOT EXISTS loans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount_given_date DATE           NOT NULL,
    created_at        TIMESTAMP(6),
    daily_installment NUMERIC(38, 2) NOT NULL,
    disbursed_amount  NUMERIC(38, 2) NOT NULL,
    end_date          DATE,
    is_active         BOOLEAN,
    principal_amount  NUMERIC(38, 2) NOT NULL,
    start_date        DATE           NOT NULL,
    tenure_days       INTEGER        NOT NULL,
    user_id           BIGINT         NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_loan_user_id ON loans (user_id);
CREATE INDEX IF NOT EXISTS idx_loan_start_date ON loans (start_date);

CREATE TABLE IF NOT EXISTS user_mirror (
    user_id         BIGINT NOT NULL PRIMARY KEY,
    care_of         VARCHAR(255),
    full_name       VARCHAR(255),
    is_active       BOOLEAN,
    last_updated_at TIMESTAMP(6),
    phone_number    VARCHAR(255),
    role            VARCHAR(255)
);
